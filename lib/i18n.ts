const DICTS: Record<Lang, Record<DictKey, string>> = { fr, en };

/** Type souple : autocomplétion des clés connues, mais clés dynamiques tolérées. */
export type TranslationKey = DictKey | (string & {});
export type Translator = (key: TranslationKey, params?: Record<string, string | number>) => string;

let activeLang: Lang = "fr";

/** Langue courante consultable hors React (journaux, validation, créations). */
export function getActiveLang(): Lang {
  return activeLang;
}

/** Réservé au provider (lib/i18n-provider.tsx). */
export function setActiveLang(lang: Lang): void {
  activeLang = lang;
}

export function translate(lang: Lang, key: TranslationKey, params?: Record<string, string | number>): string {
  const template = DICTS[lang][key as DictKey] ?? DICTS.fr[key as DictKey] ?? String(key);
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : match,
  );
}

/** Traducteur ponctuel lié à la langue active (hors React). */
export function tNow(): Translator {
  return (key, params) => translate(activeLang, key, params);
}
